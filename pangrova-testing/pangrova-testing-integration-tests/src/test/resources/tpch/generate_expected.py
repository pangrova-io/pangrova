#!/usr/bin/env python3
"""
Generate TPC-H expected results at SF=0.01 using DuckDB as reference engine.

DuckDB has built-in TPC-H data generation via the tpch extension.
Results are stored as JSON files matching the existing format used by
TpcHResultAssertions.java ({"query": "...", "rows": [...]}).

Usage: python3 generate_expected.py
"""

import duckdb
import json
import os
import sys
from pathlib import Path
from decimal import Decimal

SCALE_FACTOR = 0.01
SCRIPT_DIR = Path(__file__).parent
QUERIES_DIR = SCRIPT_DIR / "queries"
EXPECTED_DIR = SCRIPT_DIR / "expected"

QUERY_NAMES = {
    "q01": "Q1 - Pricing Summary Report",
    "q02": "Q2 - Minimum Cost Supplier",
    "q03": "Q3 - Shipping Priority",
    "q04": "Q4 - Order Priority Checking",
    "q05": "Q5 - Local Supplier Volume",
    "q06": "Q6 - Forecasting Revenue Change",
    "q07": "Q7 - Volume Shipping",
    "q08": "Q8 - National Market Share",
    "q09": "Q9 - Product Type Profit Measure",
    "q10": "Q10 - Returned Item Reporting",
    "q11": "Q11 - Important Stock Identification",
    "q12": "Q12 - Shipping Modes and Order Priority",
    "q13": "Q13 - Customer Distribution",
    "q14": "Q14 - Promotion Effect",
    "q15": "Q15 - Top Supplier",
    "q16": "Q16 - Parts/Supplier Relationship",
    "q17": "Q17 - Small-Quantity-Order Revenue",
    "q18": "Q18 - Large Volume Customer",
    "q19": "Q19 - Discounted Revenue",
    "q20": "Q20 - Potential Part Promotion",
    "q21": "Q21 - Suppliers Who Kept Orders Waiting",
    "q22": "Q22 - Global Sales Opportunity",
}


def create_tpch_database(con):
    """Generate TPC-H data at SF=0.01 using DuckDB's built-in tpch extension."""
    con.execute("INSTALL tpch")
    con.execute("LOAD tpch")
    con.execute(f"CALL dbgen(sf={SCALE_FACTOR})")
    # Verify tables exist
    tables = con.execute(
        "SELECT table_name FROM information_schema.tables WHERE table_schema='main'"
    ).fetchall()
    table_names = [t[0] for t in tables]
    print(f"Generated TPC-H tables: {table_names}")
    # Print row counts
    for t in sorted(table_names):
        count = con.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0]
        print(f"  {t}: {count} rows")


def format_value(val):
    """Format a value for JSON output with appropriate precision."""
    if val is None:
        return None
    if isinstance(val, float):
        # Round to 4 decimal places for floating point
        return round(val, 4)
    if isinstance(val, Decimal):
        return round(float(val), 4)
    if isinstance(val, int):
        return val
    # Convert date/datetime to string
    return str(val)


def execute_query(con, query_file):
    """Execute a TPC-H query and return results as list of dicts."""
    sql = (QUERIES_DIR / query_file).read_text()
    try:
        result = con.execute(sql)
        columns = [desc[0] for desc in result.description]
        rows = result.fetchall()
        return [
            {col: format_value(val) for col, val in zip(columns, row)}
            for row in rows
        ]
    except Exception as e:
        print(f"  ERROR executing {query_file}: {e}")
        return None


def write_expected(query_id, rows):
    """Write expected results to JSON file."""
    output = {
        "note": f"Generated by DuckDB at SF={SCALE_FACTOR} as reference ground truth",
        "query": QUERY_NAMES[query_id],
        "scaleFactor": SCALE_FACTOR,
        "rows": rows,
    }
    output_file = EXPECTED_DIR / f"{query_id}.json"
    with open(output_file, "w") as f:
        json.dump(output, f, indent=2, default=str)
    print(f"  Wrote {len(rows)} rows to {output_file.name}")


def main():
    print(f"Generating TPC-H expected results at SF={SCALE_FACTOR}")
    print(f"Using DuckDB as reference engine")
    print()

    # Create in-memory DuckDB with TPC-H data
    con = duckdb.connect(":memory:")
    create_tpch_database(con)
    print()

    # Execute each query and save results
    success_count = 0
    fail_count = 0
    for i in range(1, 23):
        query_id = f"q{i:02d}"
        query_file = f"{query_id}.sql"
        print(f"Executing {query_file} ({QUERY_NAMES[query_id]})...")

        rows = execute_query(con, query_file)
        if rows is not None:
            write_expected(query_id, rows)
            success_count += 1
        else:
            fail_count += 1

    print()
    print(f"Done: {success_count} succeeded, {fail_count} failed")
    con.close()

    if fail_count > 0:
        sys.exit(1)


if __name__ == "__main__":
    main()
