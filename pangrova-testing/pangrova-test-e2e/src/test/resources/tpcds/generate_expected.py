#!/usr/bin/env python3
"""
Generate TPC-DS expected results at SF=0.01 using DuckDB as reference engine.

DuckDB has built-in TPC-DS data generation via the tpcds extension.
Results are stored as JSON files matching the format used by
TpcDsTestSupport.java ({"note": "...", "query": "...", "scaleFactor": 0.01, "rows": [...]}).

Usage: python3 generate_expected.py
"""

import duckdb
import json
import os
import sys
from pathlib import Path
from decimal import Decimal

SCALE_FACTOR = 0.01
SCRIPT_DIR = Path(__file__).parent
QUERIES_DIR = SCRIPT_DIR / "queries"
EXPECTED_DIR = SCRIPT_DIR / "expected"

QUERY_NAMES = {
    "q01": "Q1 - Store Returns by Customer",
    "q03": "Q3 - Item Revenue by Brand",
    "q07": "Q7 - Promotion Revenue",
    "q13": "Q13 - Store Sales Demographics",
    "q19": "Q19 - Store Sales by Manager",
    "q25": "Q25 - Store/Catalog Returns",
    "q43": "Q43 - Store Sales by Day of Week",
    "q52": "Q52 - Web Sales by Department",
    "q55": "Q55 - Brand Revenue by Month",
    "q96": "Q96 - Store Sales by Household Demographics",
}


def create_tpcds_database(con):
    """Generate TPC-DS data at SF=0.01 using DuckDB's built-in tpcds extension."""
    con.execute("INSTALL tpcds")
    con.execute("LOAD tpcds")
    con.execute(f"CALL dsdgen(sf={SCALE_FACTOR})")
    # Verify tables exist
    tables = con.execute(
        "SELECT table_name FROM information_schema.tables WHERE table_schema='main'"
    ).fetchall()
    table_names = [t[0] for t in tables]
    print(f"Generated TPC-DS tables ({len(table_names)}): {sorted(table_names)}")
    # Print row counts for key fact tables
    for t in ["store_sales", "store_returns", "catalog_sales",
              "catalog_returns", "web_sales", "web_returns",
              "customer", "item", "date_dim"]:
        if t in table_names:
            count = con.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0]
            print(f"  {t}: {count} rows")


def format_value(val):
    """Format a value for JSON output with appropriate precision."""
    if val is None:
        return None
    if isinstance(val, float):
        # Round to 2 decimal places for floating point (TPC-DS convention)
        return round(val, 2)
    if isinstance(val, Decimal):
        return round(float(val), 2)
    if isinstance(val, int):
        return val
    # Convert date/datetime to string
    return str(val)


def execute_query(con, query_file):
    """Execute a TPC-DS query and return results as list of dicts."""
    sql = (QUERIES_DIR / query_file).read_text()
    try:
        result = con.execute(sql)
        columns = [desc[0] for desc in result.description]
        rows = result.fetchall()
        return [
            {col: format_value(val) for col, val in zip(columns, row)}
            for row in rows
        ]
    except Exception as e:
        print(f"  ERROR executing {query_file}: {e}")
        return None


def write_expected(query_id, rows):
    """Write expected results to JSON file."""
    output = {
        "note": f"Generated by DuckDB at SF={SCALE_FACTOR} as reference ground truth",
        "query": QUERY_NAMES[query_id],
        "scaleFactor": SCALE_FACTOR,
        "rows": rows,
    }
    output_file = EXPECTED_DIR / f"{query_id}.json"
    with open(output_file, "w") as f:
        json.dump(output, f, indent=2, default=str)
    print(f"  Wrote {len(rows)} rows to {output_file.name}")


def main():
    print(f"Generating TPC-DS expected results at SF={SCALE_FACTOR}")
    print(f"Using DuckDB as reference engine")
    print()

    # Create in-memory DuckDB with TPC-DS data
    con = duckdb.connect(":memory:")
    create_tpcds_database(con)
    print()

    # Execute each query and save results
    query_ids = sorted(QUERY_NAMES.keys())
    success_count = 0
    fail_count = 0
    for query_id in query_ids:
        query_file = f"{query_id}.sql"
        print(f"Executing {query_file} ({QUERY_NAMES[query_id]})...")

        rows = execute_query(con, query_file)
        if rows is not None:
            write_expected(query_id, rows)
            success_count += 1
        else:
            fail_count += 1

    print()
    print(f"Done: {success_count} succeeded, {fail_count} failed")
    con.close()

    if fail_count > 0:
        sys.exit(1)


if __name__ == "__main__":
    main()
