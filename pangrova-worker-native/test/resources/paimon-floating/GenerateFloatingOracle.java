import java.io.BufferedWriter;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Random;

/** Independent oracle: no Native formatter or reimplementation supplies expected strings. */
public final class GenerateFloatingOracle {
    private GenerateFloatingOracle() {}

    public static void main(String[] args) throws Exception {
        if (Runtime.version().feature() != 17 || args.length != 1) {
            throw new IllegalArgumentException("Run with JDK 17 and one output-file argument");
        }
        try (var output = Files.newBufferedWriter(Path.of(args[0]), StandardCharsets.UTF_8)) {
            // Every normal exponent transition, adjacent values, and both signs.
            for (int exponent = 0; exponent < 2047; exponent++) {
                for (int offset = -3; offset <= 3; offset++) {
                    long bits = ((long) exponent << 52) + offset;
                    writeDouble(output, bits);
                    writeDouble(output, bits | Long.MIN_VALUE);
                }
            }
            for (int exponent = 0; exponent < 255; exponent++) {
                for (int offset = -3; offset <= 3; offset++) {
                    int bits = (exponent << 23) + offset;
                    writeFloat(output, bits);
                    writeFloat(output, bits | Integer.MIN_VALUE);
                }
            }
            for (int bits = 1; bits < 2048; bits++) {
                writeDouble(output, bits);
                writeFloat(output, bits);
            }
            var random = new Random(71937);
            for (int index = 0; index < 2048; index++) {
                writeDouble(output, random.nextLong());
                writeFloat(output, random.nextInt());
            }
            // Legacy fixed-width stopping and decimal power boundaries.
            for (int bits : new int[] {0x6a0d83ef, 0xea083881, 0xea70fe47, 0x6a2c2e61, 0x68ff90a2}) {
                writeFloat(output, bits);
            }
            for (double value : new double[] {1e23, Math.nextUp(1e23), Math.nextDown(1e23)}) {
                writeDouble(output, Double.doubleToRawLongBits(value));
            }
        }
        System.err.println("Oracle generated by " + System.getProperty("java.vendor") + " " + Runtime.version());
    }

    private static void writeDouble(BufferedWriter output, long bits) throws Exception {
        double value = Double.longBitsToDouble(bits);
        if (Double.isFinite(value) && value != 0) {
            output.write("D " + Long.toHexString(bits) + " " + Double.toString(value) + "\n");
        }
    }

    private static void writeFloat(BufferedWriter output, int bits) throws Exception {
        float value = Float.intBitsToFloat(bits);
        if (Float.isFinite(value) && value != 0) {
            output.write("F " + Integer.toHexString(bits) + " " + Float.toString(value) + "\n");
        }
    }
}
