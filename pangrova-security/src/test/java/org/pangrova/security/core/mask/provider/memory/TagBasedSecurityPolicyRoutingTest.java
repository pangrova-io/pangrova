package org.pangrova.security.core.mask.provider.memory;

import org.pangrova.spi.security.mask.ColumnMaskRecord;
import org.pangrova.persistence.api.security.mask.ColumnMaskStore;
import org.pangrova.spi.security.UserIdentity;
import org.junit.jupiter.api.Test;

import java.time.Instant;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;

import static org.assertj.core.api.Assertions.assertThat;
import org.pangrova.security.core.mask.ColumnMaskingProcessor;

/**
 * Validates that InMemoryEnrichedColumnMaskStore correctly routes writes from
 * tag-based policy generation (via ColumnMaskStore SPI) to enforcement reads
 * (via ColumnMaskingProcessor). This proves the Task #89 fix: the same store
 * instance serves both the write path (TagBasedSecurityPolicy) and the read
 * path (ColumnMaskingProcessor enforcement).
 *
 * <p>Scenario: a tag applied to a column triggers auto-generation of a mask
 * (written via SPI saveMask) which must be immediately enforceable via
 * ColumnMaskingProcessor reading from the same store instance.</p>
 */
class TagBasedSecurityPolicyRoutingTest {

    private static final UserIdentity ANALYST = new UserIdentity(
            "alice", Set.of("analyst"), Map.of(), Instant.now());

    /**
     * Core routing test: writes via SPI ColumnMaskStore.saveMask() are visible
     * to enforcement via ColumnMaskingProcessor.getMask() on the same instance.
     */
    @Test
    void maskWrittenViaSpiIsVisibleToEnforcementProcessor() {
        // Shared store: same instance used by both writer (TagBasedSecurityPolicy) and
        // reader (ColumnMaskingProcessor). This is the fix for task #89.
        InMemoryEnrichedColumnMaskStore sharedStore = new InMemoryEnrichedColumnMaskStore();

        // ---- Write path (simulates TagBasedSecurityPolicy.applyMask) ----
        // TagBasedSecurityPolicy uses the SPI ColumnMaskStore interface
        ColumnMaskStore spiWriter = sharedStore;
        ColumnMaskRecord autoGeneratedMask = new ColumnMaskRecord(
                0, "auto_pii_email",
                "lakehouse", "public", "customers", "email",
                "mask_email", List.of(), List.of(), true, null);
        spiWriter.saveMask(autoGeneratedMask);

        // ---- Read path (enforcement via ColumnMaskingProcessor) ----
        ColumnMaskingProcessor enforcement = new ColumnMaskingProcessor(sharedStore);
        Optional<String> enforcedMask = enforcement.getMask(ANALYST, java.util.Set.of("analyst"), "lakehouse", "public", "customers", "email");

        assertThat(enforcedMask)
                .as("Mask written via SPI must be visible to enforcement processor")
                .isPresent()
                .hasValue("mask_email");
    }

    /**
     * Verifies that multiple auto-generated masks (different columns) all route correctly.
     */
    @Test
    void multipleMasksForDifferentColumnsAllRouteToEnforcement() {
        InMemoryEnrichedColumnMaskStore sharedStore = new InMemoryEnrichedColumnMaskStore();
        ColumnMaskStore spiWriter = sharedStore;
        ColumnMaskingProcessor enforcement = new ColumnMaskingProcessor(sharedStore);

        // Simulate multiple PII tags applied
        spiWriter.saveMask(new ColumnMaskRecord(0, "auto_pii_email",
                "cat", "sch", "users", "email", "mask_email", List.of(), List.of(), true, null));
        spiWriter.saveMask(new ColumnMaskRecord(0, "auto_pii_phone",
                "cat", "sch", "users", "phone", "mask_phone", List.of(), List.of(), true, null));
        spiWriter.saveMask(new ColumnMaskRecord(0, "auto_pii_ssn",
                "cat", "sch", "users", "ssn", "partial", List.of(), List.of(), true, null));

        assertThat(enforcement.getMask(ANALYST, java.util.Set.of("analyst"), "cat", "sch", "users", "email"))
                .hasValue("mask_email");
        assertThat(enforcement.getMask(ANALYST, java.util.Set.of("analyst"), "cat", "sch", "users", "phone"))
                .hasValue("mask_phone");
        assertThat(enforcement.getMask(ANALYST, java.util.Set.of("analyst"), "cat", "sch", "users", "ssn"))
                .hasValue("partial");
    }

    /**
     * Verifies that deleting a mask via SPI removes it from enforcement.
     */
    @Test
    void maskDeletedViaSpiIsRemovedFromEnforcement() {
        InMemoryEnrichedColumnMaskStore sharedStore = new InMemoryEnrichedColumnMaskStore();
        ColumnMaskStore spiWriter = sharedStore;
        ColumnMaskingProcessor enforcement = new ColumnMaskingProcessor(sharedStore);

        // Write a mask
        spiWriter.saveMask(new ColumnMaskRecord(0, "auto_pii_email",
                "cat", "sch", "users", "email", "mask_email", List.of(), List.of(), true, null));

        // Verify it's enforced
        assertThat(enforcement.getMask(ANALYST, java.util.Set.of("analyst"), "cat", "sch", "users", "email")).isPresent();

        // Read it back via SPI to get the assigned ID (simulates TagBasedSecurityPolicy.removeMask)
        List<ColumnMaskRecord> masks = spiWriter.getMasks("cat", "sch", "users", "email");
        assertThat(masks).hasSize(1);
        long maskId = masks.get(0).maskId();

        // Delete via SPI
        spiWriter.deleteMask(maskId);

        // Verify enforcement no longer sees it
        assertThat(enforcement.getMask(ANALYST, java.util.Set.of("analyst"), "cat", "sch", "users", "email")).isEmpty();
    }

    /**
     * Verifies that saveMask with the same mask name replaces (not duplicates) the mask.
     * This simulates TagBasedSecurityPolicy updating a PII type on the same column.
     */
    @Test
    void saveMaskWithSameNameReplacesExisting() {
        InMemoryEnrichedColumnMaskStore sharedStore = new InMemoryEnrichedColumnMaskStore();
        ColumnMaskStore spiWriter = sharedStore;
        ColumnMaskingProcessor enforcement = new ColumnMaskingProcessor(sharedStore);

        // Initial mask
        spiWriter.saveMask(new ColumnMaskRecord(0, "auto_pii_email",
                "cat", "sch", "users", "email", "mask_email", List.of(), List.of(), true, null));
        assertThat(enforcement.getMask(ANALYST, java.util.Set.of("analyst"), "cat", "sch", "users", "email"))
                .hasValue("mask_email");

        // Update: same mask name, different expression (PII type changed)
        spiWriter.saveMask(new ColumnMaskRecord(0, "auto_pii_email",
                "cat", "sch", "users", "email", "partial", List.of(), List.of(), true, null));
        assertThat(enforcement.getMask(ANALYST, java.util.Set.of("analyst"), "cat", "sch", "users", "email"))
                .hasValue("partial");

        // Only one mask should exist (replaced, not duplicated)
        List<ColumnMaskRecord> masks = spiWriter.getMasks("cat", "sch", "users", "email");
        assertThat(masks).hasSize(1);
    }

    /**
     * Verifies that InMemoryEnrichedColumnMaskStore is thread-safe for concurrent
     * write/read (simulating concurrent tag events and enforcement queries).
     */
    @Test
    void concurrentWriteAndReadDoesNotCorrupt() throws Exception {
        InMemoryEnrichedColumnMaskStore sharedStore = new InMemoryEnrichedColumnMaskStore();
        ColumnMaskStore spiWriter = sharedStore;
        ColumnMaskingProcessor enforcement = new ColumnMaskingProcessor(sharedStore);

        int iterations = 100;
        Thread writer = new Thread(() -> {
            for (int i = 0; i < iterations; i++) {
                spiWriter.saveMask(new ColumnMaskRecord(0, "auto_pii_col" + i,
                        "cat", "sch", "t", "col" + i, "mask_" + i, List.of(), List.of(), true, null));
            }
        });
        Thread reader = new Thread(() -> {
            for (int i = 0; i < iterations; i++) {
                // Should never throw ConcurrentModificationException
                enforcement.getMask(ANALYST, java.util.Set.of("analyst"), "cat", "sch", "t", "col" + i);
            }
        });

        writer.start();
        reader.start();
        writer.join(5000);
        reader.join(5000);

        // After concurrent operations, all written masks should be readable
        for (int i = 0; i < iterations; i++) {
            assertThat(enforcement.getMask(ANALYST, java.util.Set.of("analyst"), "cat", "sch", "t", "col" + i))
                    .as("Mask for col%d should be present after concurrent write/read", i)
                    .isPresent();
        }
    }
}
