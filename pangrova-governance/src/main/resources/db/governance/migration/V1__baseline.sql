-- Name: quality_rules; Type: TABLE; Schema: public; Owner: -

CREATE TABLE quality_rules (
    rule_id bigint NOT NULL,
    rule_name character varying(512) NOT NULL,
    catalog_name character varying(255) NOT NULL,
    schema_name character varying(255) NOT NULL,
    table_name character varying(255) NOT NULL,
    check_expression text NOT NULL,
    severity character varying(32) NOT NULL,
    message character varying(1024),
    enabled boolean DEFAULT true NOT NULL,
    schedule character varying(128),
    created_at timestamp without time zone NOT NULL,
    updated_at timestamp without time zone NOT NULL,
    execution_principal character varying(512),
    execution_tenant character varying(255),
    table_id uuid,
    CONSTRAINT quality_rule_execution_identity CHECK ((((execution_principal IS NULL) AND (execution_tenant IS NULL) AND (NOT enabled)) OR ((execution_principal IS NOT NULL) AND (length(TRIM(BOTH FROM execution_principal)) > 0) AND (execution_tenant IS NOT NULL) AND (length(TRIM(BOTH FROM execution_tenant)) > 0))))
);

